import { sql } from 'drizzle-orm';
import {
  type AnyPgColumn,
  boolean,
  check,
  customType,
  index,
  integer,
  pgEnum,
  pgTable,
  text,
  uuid,
} from 'drizzle-orm/pg-core';
import { idColumn, liveUnique, seedKeyColumn, seedKeyUnique } from '../../../db/schema-parts';
import { auditColumns } from '../../identity/schema/users';

export const helpArticleKind = pgEnum('help_article_kind', ['faq', 'article', 'term']);
// Who may read a row: anyone, site keepers and curators, or site keepers alone.
export const helpAudience = pgEnum('help_audience', ['public', 'staff', 'keeper']);

const tsvector = customType<{ data: string }>({ dataType: () => 'tsvector' });

// A page of the Help section, an FAQ entry or a glossary term. The service, not the database, enforces that a parent is a row of kind `article`
// and that nesting is one level deep. `search_vector` is generated by the database from the title, summary, search terms and body.
export const helpArticles = pgTable(
  'help_articles',
  {
    id: idColumn(),
    kind: helpArticleKind('kind').notNull(),
    audience: helpAudience('audience').notNull().default('public'),
    title: text('title').notNull(),
    slug: text('slug').notNull(),
    summary: text('summary'),
    // Words a keeper adds so a reader's own word finds the row, such as "poisonous" for a page that says "toxic"; indexed beside the summary.
    searchTerms: text('search_terms'),
    body: text('body').notNull(),
    position: integer('position'),
    seedKey: seedKeyColumn(),
    parentId: uuid('parent_id').references((): AnyPgColumn => helpArticles.id),
    // Whether readers see the row. A hidden row is kept for the keepers, never deleted; a hidden parent hides its children too.
    shown: boolean('shown').notNull().default(true),
    searchVector: tsvector('search_vector').generatedAlwaysAs(
      (): ReturnType<typeof sql> =>
        sql`setweight(to_tsvector('english', title), 'A') || setweight(to_tsvector('english', coalesce(summary, '')), 'B') || setweight(to_tsvector('english', coalesce(search_terms, '')), 'B') || setweight(to_tsvector('english', body), 'C')`,
    ),
    ...auditColumns,
  },
  (table) => [
    liveUnique('help_articles_slug_unique', table, table.kind, table.slug),
    seedKeyUnique('help_articles_seed_key_unique', table),
    index('help_articles_search_vector_idx').using('gin', table.searchVector),
    // A glossary term has no order and no parent, and is public.
    check(
      'help_articles_term_no_position',
      sql`${table.kind} <> 'term' or ${table.position} is null`,
    ),
    check(
      'help_articles_term_no_parent',
      sql`${table.kind} <> 'term' or ${table.parentId} is null`,
    ),
    check('help_articles_not_own_parent', sql`${table.parentId} is distinct from ${table.id}`),
    check(
      'help_articles_term_public',
      sql`${table.kind} <> 'term' or ${table.audience} = 'public'`,
    ),
  ],
);
